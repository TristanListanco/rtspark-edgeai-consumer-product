#!/usr/bin/env python3
"""Render an 8x16 1-bpp bitmap font (ASCII 0x20-0x7E) for the LCD driver.

Source font: DejaVu Sans Mono Bold (Bitstream Vera / DejaVu license, redistributable),
taken from matplotlib's bundled fonts so no extra download is needed.

Usage:
    .venv/bin/python scripts/gen_font.py > src/drivers/font8x16.c
"""
import os
import sys

import matplotlib
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
FIRST, LAST = 0x20, 0x7E
FONT_FILE = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf",
                         "DejaVuSansMono-Bold.ttf")
FONT_PX = 13      # glyph advance ~7.8 px at 13 px -> fits an 8 px cell
THRESHOLD = 110   # anti-aliased coverage above this becomes a lit pixel


def render(ch: str, font: ImageFont.FreeTypeFont) -> list[int]:
    img = Image.new("L", (W, H), 0)
    draw = ImageDraw.Draw(img)
    ascent, _ = font.getmetrics()
    draw.text((0, 13 - ascent), ch, font=font, fill=255)  # baseline at row 13
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if img.getpixel((x, y)) > THRESHOLD:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


def main() -> int:
    font = ImageFont.truetype(FONT_FILE, FONT_PX)
    out = sys.stdout
    out.write("/* Generated by scripts/gen_font.py - do not edit.\n"
              " * 8x16 bitmap of DejaVu Sans Mono Bold, ASCII 0x20-0x7E, MSB = leftmost pixel.\n"
              " * DejaVu fonts: Bitstream Vera license + public-domain DejaVu changes. */\n")
    out.write('#include "drivers/font8x16.h"\n\n')
    out.write(f"const uint8_t font8x16[{LAST - FIRST + 1}][{H}] = {{\n")
    for code in range(FIRST, LAST + 1):
        rows = render(chr(code), font)
        label = chr(code) if chr(code) not in "\\'" else "\\" + chr(code)
        out.write("    {" + ", ".join(f"0x{r:02x}" for r in rows) + f"}}, /* '{label}' */\n")
    out.write("};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
